import { readdir, readFile, writeFile } from 'node:fs/promises';
const types = { '.html': 'text/html; charset=utf-8', '.css': 'text/css; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.txt': 'text/plain; charset=utf-8' };
const assets = {};
for (const name of await readdir('public')) {
  const type = types[name.slice(name.lastIndexOf('.'))];
  if (!type) throw new Error(`Unexpected public asset: ${name}`);
  assets['/' + name] = { type, content: await readFile('public/' + name, 'utf8') };
}
await writeFile('src/generated-assets.mjs', '// Generated by scripts/build-assets.mjs; edit public/ instead.\n/** @type {Record<string, {type: string, content: string}>} */\nexport const assets = ' + JSON.stringify(assets) + ';\n');
console.log(`Bundled ${Object.keys(assets).length} public assets.`);
